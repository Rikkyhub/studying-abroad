def issue_map_markdown(root: Path = ROOT) -> str:
    def issue_cell(url: str) -> str:
        m = re.search(r"/issues/(\d+)$", url)
        return f"[#{m.group(1)}]({url})" if m else "－"
    out = ["# Issue対応表（AI・保守者向け）", "",
           "このページは保守者とAIが資料・タスクと GitHub Issue の対応を確認するための一覧です。閲覧者向けのダッシュボードの表には出していません。"
           "正本は `data/pages.csv` の `issue` 列と `data/tasks.csv` の `issue` 列で、このページは `py scripts/build_all.py` が生成します。手で編集しないでください。", "",
           "## 資料と Issue", "", "| 資料 | Issue | 状態 | 最終確認日 |", "|---|---|---|---|"]
    for r in sorted_pages(root):
        out.append(f"| [{r['title']}](../{r['path']}) | {issue_cell(r['issue'])} | {PAGE_STATUS.get(r['status'], r['status'])} | {r['verified_at'] or '－'} |")
    out += ["", "## タスクと Issue", "", "| ID | 優先 | 作業 | Issue | 状態 |", "|---|---|---|---|---|"]
    for r in csv_records(root / DATA_DIR / "tasks.csv"):
        out.append(f"| {r['id']} | {r['priority']} | {r['task']} | {issue_cell(r['issue'])} | {r['status']} |")
    return "\n".join(out) + "\n"


def fill_auto(text: str, name: str, content: str) -> str:
    pat = re.compile(rf"(<!-- AUTO:{name} -->)(.*?)(<!-- /AUTO:{name} -->)", re.S)
    return pat.sub(lambda m: f"{m.group(1)}\n{content}\n{m.group(3)}", text)


def main() -> int:
    check_only = "--check" in sys.argv
    out = outputs()
    if check_only:
        stale = [p.relative_to(ROOT).as_posix() for p, text in out.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        orphan = [p.relative_to(ROOT).as_posix() for d in SOURCE_DIRS + [DATA_DIR] for p in (ROOT / d).glob("*.html")
                  if p.read_text(encoding="utf-8").startswith("<!doctype html>\n<!-- generated") and p not in out]
        if stale or orphan:
            print("HTML が Markdown と一致しません。`python3 scripts/build_html.py` を実行してコミットしてください: "
                  + ", ".join(stale + orphan), file=sys.stderr)
            return 1
        print(f"PASS: {len(out)} HTML pages match Markdown")
        return 0
    for p, text in out.items():
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"更新しました: {len(out)} ページ")
    return 0


