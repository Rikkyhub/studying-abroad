def nav(root: Path, current: Path) -> str:
    """ページ下部の全ページ一覧（グループ見出し＋リンク）。CSV 由来のページは含めない"""
    parts = []
    for d, label in GROUPS.items():
        links = []
        for f in sorted((root / d).glob("*.md")):
            cur = ' aria-current="page"' if f == current else ""
            links.append(f'<a href="../{d}/{f.stem}.html"{cur}>{html.escape(page_title(f))}</a>')
        if links:
            parts.append(f'<div><div class="g">{label}</div>{"".join(links)}</div>')
        if d == "areas":
            here = f"{current.parent.name}/{current.name}"
            cur = ' aria-current="page"'
            maps = "".join(f'<a href="../maps/{n}.html"{cur if here == f"maps/{n}.html" else ""}>{t}</a>' for n, t in MAP_PAGES)
            parts.append(f'<div><div class="g">{MAP_GROUP}</div>{maps}</div>')
    return "".join(parts)


def page_title(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^#\s+(.*)$", line.strip())
        if m:
            return re.sub(r"[*`]", "", m.group(1)).strip()
    return path.stem


def render(path: Path, root: Path = ROOT) -> str:
    return render_text(path.read_text(encoding="utf-8"), path, root)


def render_text(md: str, path: Path, root: Path = ROOT) -> str:
    title, body, toc = convert(md)
    title = title or path.stem
    rel = path.relative_to(root).as_posix()
    toc_html = ""
    heads = [(a, t) for lv, a, t in toc if lv == 2]
    if len(heads) >= 3:
        toc_html = '<nav class="toc" aria-label="このページの目次"><span class="label">このページ：</span>' + "".join(
            f'<a href="#{a}">{html.escape(t)}</a>' for a, t in heads) + "</nav>"
    current = f"{path.parent.name}/{path.stem}.html" if path.parent.name == "areas" else ""
    return page_html(
        mark=GENERATED_MARK.format(src=rel),
        title=html.escape(title),
        section=GROUPS.get(path.parent.name, ""),
        body=body,
        toc=toc_html,
        bar=bar("../", current),
        prefix="../",
        nav=nav(root, path),
        src=html.escape(rel),
        src_url=f"{REPO_URL}/blob/main/{rel}",
    )


