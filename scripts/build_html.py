# ---------------------------------------------------------------- inline
def rewrite_href(href: str) -> str:
    """同じリポジトリ内の .md へのリンクは生成された .html に向ける"""
    if re.match(r"^[a-z]+:", href) or href.startswith("#"):
        return href
    path, sep, frag = href.partition("#")
    if path.endswith(".md") and Path(path).name not in ("README.md", "AGENTS.md", "CLAUDE.md"):
        path = path[:-3] + ".html"
    return path + sep + frag


def inline(text: str) -> str:
    codes: list[str] = []

    def keep_code(m):
        codes.append(f"<code>{html.escape(m.group(1))}</code>")
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", keep_code, text)
    links: list[str] = []

    def keep_link(m):
        label, href = m.group(1), m.group(2).strip()
        ext = re.match(r"^https?:", href)
        attrs = ' target="_blank" rel="noopener"' if ext else ""
        links.append(f'<a href="{html.escape(rewrite_href(href), quote=True)}"{attrs}>{inline_plain(label)}</a>')
        return f"\x01{len(links) - 1}\x01"

    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", keep_link, text)

    def keep_url(m):
        url = m.group(0)
        links.append(f'<a href="{html.escape(url, quote=True)}" target="_blank" rel="noopener">{html.escape(url)}</a>')
        return f"\x01{len(links) - 1}\x01"

    text = re.sub(r"https?://[^\s|）)<>、。]+", keep_url, text)
    text = inline_plain(text)
    text = re.sub(r"\x01(\d+)\x01", lambda m: links[int(m.group(1))], text)
    return re.sub(r"\x00(\d+)\x00", lambda m: codes[int(m.group(1))], text)


def inline_plain(text: str) -> str:
    keep = re.findall(r"[\x00\x01]\d+[\x00\x01]", text)
    text = html.escape(text, quote=False)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*([^*\s][^*]*?)\*(?![\w*])", r"<em>\1</em>", text)
    text = text.replace("&lt;br&gt;", "<br>")
    assert len(keep) == len(re.findall(r"[\x00\x01]\d+[\x00\x01]", text))
    return text


# ---------------------------------------------------------------- blocks
def split_row(line: str) -> list[str]:
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in line.split("|")]


def slug(text: str, used: dict) -> str:
    s = re.sub(r"<[^>]+>", "", text)
    s = re.sub(r"[\s　]+", "-", s.strip())
    s = re.sub(r"[^\w\-ぁ-んァ-ヶ一-龠ー]", "", s).lower() or "section"
    n = used.get(s, 0)
    used[s] = n + 1
    return s if n == 0 else f"{s}-{n}"


def convert(md: str) -> tuple[str, str, list[tuple[int, str, str]]]:
    """Markdown -> (title, body_html, toc)"""
    md = re.sub(r"<!--.*?-->", "", md, flags=re.S)
    lines = md.replace("\r\n", "\n").split("\n")
    out: list[str] = []
    toc: list[tuple[int, str, str]] = []
    used: dict = {}
    title = ""
    i = 0
    para: list[str] = []

    def flush():
        if para:
            out.append("<p>" + "<br>\n".join(inline(p) for p in para) + "</p>")
            para.clear()

    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if not s:
            flush(); i += 1; continue
        if s.startswith("```"):
            flush()
            lang = s[3:].strip()
            buf = []
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                buf.append(lines[i]); i += 1
            i += 1
            cls = f' class="lang-{html.escape(lang)}"' if lang else ""
            out.append(f"<pre><code{cls}>{html.escape(chr(10).join(buf))}</code></pre>")
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", s)
        if m:
            flush()
            level, text = len(m.group(1)), inline(m.group(2).strip())
            if level == 1 and not title:
                title = re.sub(r"<[^>]+>", "", text)
                i += 1
                continue
            anchor = slug(text, used)
            if level <= 3:
                toc.append((level, anchor, re.sub(r"<[^>]+>", "", text)))
            out.append(f'<h{level} id="{anchor}">{text}</h{level}>')
            i += 1
            continue
        if re.match(r"^(-{3,}|\*{3,})$", s):
            flush(); out.append("<hr>"); i += 1; continue
        if s.startswith("|") and i + 1 < len(lines) and re.match(r"^\|?\s*:?-{2,}", lines[i + 1].strip()):
            flush()
            head = split_row(s)
            aligns = []
            for c in split_row(lines[i + 1]):
                aligns.append("right" if c.endswith(":") and not c.startswith(":") else "center" if c.startswith(":") and c.endswith(":") else "")
            i += 2
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(split_row(lines[i])); i += 1

            def cell(tag, c, k):
                a = aligns[k] if k < len(aligns) else ""
                st = f' class="{"n" if a == "right" else "c"}"' if a else ""
                return f"<{tag}{st}>{inline(c)}</{tag}>"
            thead = "<tr>" + "".join(cell("th", c, k) for k, c in enumerate(head)) + "</tr>"
            tbody = "".join("<tr>" + "".join(cell("td", c, k) for k, c in enumerate(r)) + "</tr>" for r in rows)
            out.append(f'<div class="scroll"><table><thead>{thead}</thead><tbody>{tbody}</tbody></table></div>')
            continue
        if s.startswith(">"):
            flush()
            buf = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                buf.append(lines[i].strip()[1:].strip()); i += 1
            out.append("<blockquote><p>" + "<br>\n".join(inline(b) for b in buf if b) + "</p></blockquote>")
            continue
        lm = re.match(r"^(\s*)([-*]|\d+\.)\s+(.*)$", line)
        if lm:
            flush()
            out.append(list_block(lines, i))
            while i < len(lines) and (re.match(r"^\s*([-*]|\d+\.)\s+", lines[i]) or (lines[i].startswith("  ") and lines[i].strip())):
                i += 1
            continue
        para.append(s)
        i += 1
    flush()
    return title, "\n".join(out), toc


def list_block(lines: list[str], i: int) -> str:
    """インデント（2スペース以上）で入れ子にした箇条書きを変換する"""
    items: list[tuple[int, bool, str]] = []
    while i < len(lines):
        m = re.match(r"^(\s*)([-*]|\d+\.)\s+(.*)$", lines[i])
        if m:
            items.append((len(m.group(1).replace("\t", "    ")), m.group(2)[0].isdigit(), m.group(3)))
        elif lines[i].startswith("  ") and lines[i].strip() and items:
            ind, ordered, text = items[-1]
            items[-1] = (ind, ordered, text + " " + lines[i].strip())
        else:
            break
        i += 1
    html_out: list[str] = []
    stack: list[tuple[int, str]] = []
    for ind, ordered, text in items:
        tag = "ol" if ordered else "ul"
        while stack and ind < stack[-1][0]:
            html_out.append(f"</li></{stack.pop()[1]}>")
        if not stack or ind > stack[-1][0]:
            html_out.append(f"<{tag}>")
            stack.append((ind, tag))
        else:
            html_out.append("</li>")
        m = re.match(r"^\[( |x|X)\]\s+(.*)$", text)
        if m:
            done = m.group(1) != " "
            text_html = f'<span class="check{" done" if done else ""}" aria-label="{"完了" if done else "未完了"}"></span>{inline(m.group(2))}'
        else:
            text_html = inline(text)
        html_out.append(f"<li>{text_html}")
    while stack:
        html_out.append(f"</li></{stack.pop()[1]}>")
    return "".join(html_out).replace("<ul></li>", "<ul>").replace("<ol></li>", "<ol>")


