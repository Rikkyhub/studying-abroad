def nav(root: Path, current: Path) -> str:
    """ページ下部の全ページ一覧（グループ見出し＋リンク）。CSV 由来のページは含めない"""
    parts = []
    for d, label in GROUPS.items():
        # research/archive-*.md は『過去の比較案』として別の折りたたみにする（現行の資料と混ぜない）
        for suffix, glabel, keep in (("", label, lambda n: not n.startswith(ARCHIVE_PREFIX)),
                                     ("-old", ARCHIVE_GROUP, lambda n: n.startswith(ARCHIVE_PREFIX))):
            if suffix and d != "research":
                continue
            links = []
            for f in sorted((root / d).glob("*.md")):
                if not keep(f.stem):
                    continue
                cur = ' aria-current="page"' if f == current else ""
                links.append(f'<a href="../{d}/{f.stem}.html"{cur}>{html.escape(page_title(f))}</a>')
            if links:
                has_cur = any("aria-current" in x for x in links)
                parts.append(f'<details class="g-fold"{" open" if has_cur else ""}><summary>{glabel}（{len(links)}）</summary>{"".join(links)}</details>')
        if d == "areas":
            here = f"{current.parent.name}/{current.name}"
            cur = ' aria-current="page"'
            maps = "".join(f'<a href="../maps/{n}.html"{cur if here == f"maps/{n}.html" else ""}>{t}</a>' for n, t in MAP_PAGES)
            parts.append(f'<details class="g-fold"{" open" if here.startswith("maps/") else ""}><summary>{MAP_GROUP}（{len(MAP_PAGES)}）</summary>{maps}</details>')
    return "".join(parts)


def page_title(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^#\s+(.*)$", line.strip())
        if m:
            return re.sub(r"[*`]", "", m.group(1)).strip()
    return path.stem


def render(path: Path, root: Path = ROOT) -> str:
    return render_text(path.read_text(encoding="utf-8"), path, root)


