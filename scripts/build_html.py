# ---------------------------------------------------------------- inline
def rewrite_href(href: str) -> str:
    """同じリポジトリ内の .md へのリンクは生成された .html に向ける"""
    if re.match(r"^[a-z]+:", href) or href.startswith("#"):
        return href
    path, sep, frag = href.partition("#")
    if path.endswith(".md") and Path(path).name not in ("README.md", "AGENTS.md", "CLAUDE.md"):
        path = path[:-3] + ".html"
    return path + sep + frag


def inline(text: str) -> str:
    codes: list[str] = []

    def keep_code(m):
        codes.append(f"<code>{html.escape(m.group(1))}</code>")
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", keep_code, text)
    links: list[str] = []

    def keep_link(m):
        label, href = m.group(1), m.group(2).strip()
        ext = re.match(r"^https?:", href)
        attrs = ' target="_blank" rel="noopener"' if ext else ""
        links.append(f'<a href="{html.escape(rewrite_href(href), quote=True)}"{attrs}>{inline_plain(label)}</a>')
        return f"\x01{len(links) - 1}\x01"

    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", keep_link, text)

    def keep_url(m):
        url = m.group(0)
        links.append(f'<a href="{html.escape(url, quote=True)}" target="_blank" rel="noopener">{html.escape(url)}</a>')
        return f"\x01{len(links) - 1}\x01"

    text = re.sub(r"https?://[^\s|）)<>、。]+", keep_url, text)
    text = inline_plain(text)
    text = re.sub(r"\x01(\d+)\x01", lambda m: links[int(m.group(1))], text)
    return re.sub(r"\x00(\d+)\x00", lambda m: codes[int(m.group(1))], text)


def inline_plain(text: str) -> str:
    keep = re.findall(r"[\x00\x01]\d+[\x00\x01]", text)
    text = html.escape(text, quote=False)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*([^*\s][^*]*?)\*(?![\w*])", r"<em>\1</em>", text)
    text = text.replace("&lt;br&gt;", "<br>")
    assert len(keep) == len(re.findall(r"[\x00\x01]\d+[\x00\x01]", text))
    return text


# ---------------------------------------------------------------- blocks
def split_row(line: str) -> list[str]:
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in line.split("|")]


def slug(text: str, used: dict) -> str:
    s = re.sub(r"<[^>]+>", "", text)
    s = re.sub(r"[\s　]+", "-", s.strip())
    s = re.sub(r"[^\w\-ぁ-んァ-ヶ一-龠ー]", "", s).lower() or "section"
    n = used.get(s, 0)
    used[s] = n + 1
    return s if n == 0 else f"{s}-{n}"


def collapse_long(html_str: str, limit: int = 120, head: int = 70) -> str:
    """長い文は先頭だけを見せ、全文は開いて読めるようにする（段階的な表示）。短い文はそのまま"""
    plain = html.unescape(re.sub(r"<[^>]+>", "", html_str)).strip()
    if len(plain) <= limit:
        return html_str
    return (f'<details class="more"><summary>{html.escape(plain[:head].rstrip())}…<span class="hint">（全文を開く）</span></summary>'
            f'<div class="full">{html_str}</div></details>')


def fold_notes(body: str, keep: int = 2) -> str:
    """「前提と備考」直後の長い箇条書きは、先頭 keep 件だけ見せて残りを開閉にする"""
    def repl(m):
        items = re.findall(r"<li>.*?</li>", m.group(2), re.S)
        if len(items) <= keep:
            return m.group(0)
        head, rest = "".join(items[:keep]), "".join(items[keep:])
        return (m.group(1) + f"<ul>{head}</ul>"
                f'<details class="more notes"><summary>残り {len(items) - keep} 件の前提・備考を開く</summary><ul>{rest}</ul></details>')
    return re.sub(r"(<p><strong>前提と備考</strong></p>\s*)<ul>(.*?)</ul>", repl, body, flags=re.S)


def fold_sections(body: str, min_chars: int = 600, open_key: str = "") -> str:
    """長いページ：h2 の節ごとに開閉できるようにする。open_key を含む見出しの節（なければ最初の長い節）だけ開いておく"""
    parts = re.split(r'(?=<h2 id=)', body)
    out, opened, n = [parts[0]], False, 0
    for p in parts[1:]:
        m = re.match(r'(<h2 id="[^"]+">.*?</h2>)(.*)$', p, re.S)
        if m and len(re.sub(r"<[^>]+>", "", m.group(2))) > min_chars:
            want = (open_key in m.group(1)) if open_key else not opened
            op = " open" if want and not opened else ""
            opened, n = opened or want, n + 1
            out.append(f'<details class="sec"{op}><summary>{m.group(1)}</summary>{m.group(2)}</details>')
        else:
            out.append(p)
    res = "".join(out)
    if n >= 2:
        res = ('<p class="sec-tools"><button type="button" data-sec="open">すべての節を開く</button> '
               '<button type="button" data-sec="close">すべての節を閉じる</button></p>\n') + res
    return res


