# -*- coding: utf-8 -*-
"""Markdown（research/・docs/・blog/）をブラウザで読める静的HTMLに変換する。

使い方（リポジトリのルートで実行）:
    python3 scripts/build_html.py           HTMLを再生成
    python3 scripts/build_html.py --check   HTMLがMarkdownと一致しなければ失敗（CI用）

- 正本は Markdown。HTML は生成物なので手で編集しない。
- 標準ライブラリのみ。リポジトリで使っている記法（見出し・段落・箇条書き・表・
  太字・インラインコード・リンク・コードブロック・引用・区切り線）だけに対応する。
"""
from __future__ import annotations

import csv
import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIRS = ["research", "docs", "blog"]
DATA_DIR = "data"
GROUPS = {"research": "現地調査", "docs": "計画・費用", "blog": "ブログ", "data": "データ（CSV）"}
GENERATED_MARK = "<!-- generated by scripts/build_html.py from {src}; do not edit -->"
REPO_URL = "https://github.com/Rikkyhub/studying-abroad"


def sources(root: Path = ROOT) -> list[Path]:
    out = []
    for d in SOURCE_DIRS:
        out += sorted(p for p in (root / d).glob("*.md"))
    return out


# ---------------------------------------------------------------- inline
def rewrite_href(href: str) -> str:
    """同じリポジトリ内の .md へのリンクは生成された .html に向ける"""
    if re.match(r"^[a-z]+:", href) or href.startswith("#"):
        return href
    path, sep, frag = href.partition("#")
    if path.endswith(".md") and Path(path).name != "README.md":
        path = path[:-3] + ".html"
    return path + sep + frag


def inline(text: str) -> str:
    codes: list[str] = []

    def keep_code(m):
        codes.append(f"<code>{html.escape(m.group(1))}</code>")
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", keep_code, text)
    links: list[str] = []

    def keep_link(m):
        label, href = m.group(1), m.group(2).strip()
        ext = re.match(r"^https?:", href)
        attrs = ' target="_blank" rel="noopener"' if ext else ""
        links.append(f'<a href="{html.escape(rewrite_href(href), quote=True)}"{attrs}>{inline_plain(label)}</a>')
        return f"\x01{len(links) - 1}\x01"

    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", keep_link, text)

    def keep_url(m):
        url = m.group(0)
        links.append(f'<a href="{html.escape(url, quote=True)}" target="_blank" rel="noopener">{html.escape(url)}</a>')
        return f"\x01{len(links) - 1}\x01"

    text = re.sub(r"https?://[^\s|）)<>、。]+", keep_url, text)
    text = inline_plain(text)
    text = re.sub(r"\x01(\d+)\x01", lambda m: links[int(m.group(1))], text)
    return re.sub(r"\x00(\d+)\x00", lambda m: codes[int(m.group(1))], text)


def inline_plain(text: str) -> str:
    keep = re.findall(r"[\x00\x01]\d+[\x00\x01]", text)
    text = html.escape(text, quote=False)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*([^*\s][^*]*?)\*(?![\w*])", r"<em>\1</em>", text)
    text = text.replace("&lt;br&gt;", "<br>")
    assert len(keep) == len(re.findall(r"[\x00\x01]\d+[\x00\x01]", text))
    return text


# ---------------------------------------------------------------- blocks
def split_row(line: str) -> list[str]:
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in line.split("|")]


def slug(text: str, used: dict) -> str:
    s = re.sub(r"<[^>]+>", "", text)
    s = re.sub(r"[\s　]+", "-", s.strip())
    s = re.sub(r"[^\w\-ぁ-んァ-ヶ一-龠ー]", "", s).lower() or "section"
    n = used.get(s, 0)
    used[s] = n + 1
    return s if n == 0 else f"{s}-{n}"


def convert(md: str) -> tuple[str, str, list[tuple[int, str, str]]]:
    """Markdown -> (title, body_html, toc)"""
    md = re.sub(r"<!--.*?-->", "", md, flags=re.S)
    lines = md.replace("\r\n", "\n").split("\n")
    out: list[str] = []
    toc: list[tuple[int, str, str]] = []
    used: dict = {}
    title = ""
    i = 0
    para: list[str] = []

    def flush():
        if para:
            out.append("<p>" + "<br>\n".join(inline(p) for p in para) + "</p>")
            para.clear()

    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if not s:
            flush(); i += 1; continue
        if s.startswith("```"):
            flush()
            lang = s[3:].strip()
            buf = []
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                buf.append(lines[i]); i += 1
            i += 1
            cls = f' class="lang-{html.escape(lang)}"' if lang else ""
            out.append(f"<pre><code{cls}>{html.escape(chr(10).join(buf))}</code></pre>")
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", s)
        if m:
            flush()
            level, text = len(m.group(1)), inline(m.group(2).strip())
            if level == 1 and not title:
                title = re.sub(r"<[^>]+>", "", text)
                i += 1
                continue
            anchor = slug(text, used)
            if level <= 3:
                toc.append((level, anchor, re.sub(r"<[^>]+>", "", text)))
            out.append(f'<h{level} id="{anchor}">{text}</h{level}>')
            i += 1
            continue
        if re.match(r"^(-{3,}|\*{3,})$", s):
            flush(); out.append("<hr>"); i += 1; continue
        if s.startswith("|") and i + 1 < len(lines) and re.match(r"^\|?\s*:?-{2,}", lines[i + 1].strip()):
            flush()
            head = split_row(s)
            aligns = []
            for c in split_row(lines[i + 1]):
                aligns.append("right" if c.endswith(":") and not c.startswith(":") else "center" if c.startswith(":") and c.endswith(":") else "")
            i += 2
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(split_row(lines[i])); i += 1

            def cell(tag, c, k):
                a = aligns[k] if k < len(aligns) else ""
                st = f' class="{"n" if a == "right" else "c"}"' if a else ""
                return f"<{tag}{st}>{inline(c)}</{tag}>"
            thead = "<tr>" + "".join(cell("th", c, k) for k, c in enumerate(head)) + "</tr>"
            tbody = "".join("<tr>" + "".join(cell("td", c, k) for k, c in enumerate(r)) + "</tr>" for r in rows)
            out.append(f'<div class="scroll"><table><thead>{thead}</thead><tbody>{tbody}</tbody></table></div>')
            continue
        if s.startswith(">"):
            flush()
            buf = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                buf.append(lines[i].strip()[1:].strip()); i += 1
            out.append("<blockquote><p>" + "<br>\n".join(inline(b) for b in buf if b) + "</p></blockquote>")
            continue
        lm = re.match(r"^(\s*)([-*]|\d+\.)\s+(.*)$", line)
        if lm:
            flush()
            out.append(list_block(lines, i))
            while i < len(lines) and (re.match(r"^\s*([-*]|\d+\.)\s+", lines[i]) or (lines[i].startswith("  ") and lines[i].strip())):
                i += 1
            continue
        para.append(s)
        i += 1
    flush()
    return title, "\n".join(out), toc


def list_block(lines: list[str], i: int) -> str:
    """インデント（2スペース以上）で入れ子にした箇条書きを変換する"""
    items: list[tuple[int, bool, str]] = []
    while i < len(lines):
        m = re.match(r"^(\s*)([-*]|\d+\.)\s+(.*)$", lines[i])
        if m:
            items.append((len(m.group(1).replace("\t", "    ")), m.group(2)[0].isdigit(), m.group(3)))
        elif lines[i].startswith("  ") and lines[i].strip() and items:
            ind, ordered, text = items[-1]
            items[-1] = (ind, ordered, text + " " + lines[i].strip())
        else:
            break
        i += 1
    html_out: list[str] = []
    stack: list[tuple[int, str]] = []
    for ind, ordered, text in items:
        tag = "ol" if ordered else "ul"
        while stack and ind < stack[-1][0]:
            html_out.append(f"</li></{stack.pop()[1]}>")
        if not stack or ind > stack[-1][0]:
            html_out.append(f"<{tag}>")
            stack.append((ind, tag))
        else:
            html_out.append("</li>")
        m = re.match(r"^\[( |x|X)\]\s+(.*)$", text)
        if m:
            done = m.group(1) != " "
            text_html = f'<span class="check{" done" if done else ""}" aria-label="{"完了" if done else "未完了"}"></span>{inline(m.group(2))}'
        else:
            text_html = inline(text)
        html_out.append(f"<li>{text_html}")
    while stack:
        html_out.append(f"</li></{stack.pop()[1]}>")
    return "".join(html_out).replace("<ul></li>", "<ul>").replace("<ol></li>", "<ol>")


# ---------------------------------------------------------------- page
def nav(root: Path, current: Path) -> str:
    groups = GROUPS
    rel_root = "../"
    parts = [f'<a href="{rel_root}index.html">ダッシュボード</a>']
    for d, label in groups.items():
        files = sorted((root / d).glob("*.csv" if d == DATA_DIR else "*.md"))
        links = []
        for f in files:
            t = f.name if d == DATA_DIR else page_title(f)
            href = f"{rel_root}{d}/{f.stem}.html"
            cur = ' aria-current="page"' if f == current else ""
            links.append(f'<a href="{href}"{cur}>{html.escape(t)}</a>')
        parts.append(f'<details{" open" if current.parent.name == d else ""}><summary>{label}</summary>{"".join(links)}</details>')
    return "".join(parts)


def page_title(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^#\s+(.*)$", line.strip())
        if m:
            return re.sub(r"[*`]", "", m.group(1)).strip()
    return path.stem


def render(path: Path, root: Path = ROOT) -> str:
    return render_text(path.read_text(encoding="utf-8"), path, root)


def render_text(md: str, path: Path, root: Path = ROOT) -> str:
    title, body, toc = convert(md)
    title = title or path.stem
    rel = path.relative_to(root).as_posix()
    toc_html = "".join(f'<a class="t{lv}" href="#{a}">{html.escape(t)}</a>' for lv, a, t in toc if lv <= 3)
    return PAGE.format(
        mark=GENERATED_MARK.format(src=rel),
        title=html.escape(title),
        section=GROUPS.get(path.parent.name, ""),
        body=body,
        toc=toc_html or "",
        toc_hidden="" if len(toc) > 2 else " hidden",
        nav=nav(root, path),
        src=html.escape(rel),
        src_url=f"{REPO_URL}/blob/main/{rel}",
    )


def csv_files(root: Path = ROOT) -> list[Path]:
    return sorted((root / DATA_DIR).glob("*.csv"))


def read_csv_rows(path: Path) -> tuple[list[str], list[list[str]]]:
    with path.open(newline="", encoding="utf-8-sig") as f:
        rows = list(csv.reader(f))
    return (rows[0], rows[1:]) if rows else ([], [])


def csv_to_markdown(path: Path, root: Path = ROOT) -> str:
    """CSV を Markdown の表にする。セル内の | と改行は表を壊さないよう置き換える"""
    head, rows = read_csv_rows(path)
    rel = path.relative_to(root).as_posix()

    def cell(v: str) -> str:
        return " ".join(v.replace("|", "／").split())
    out = [f"# {path.name}", "",
           f"`{rel}` を表にした閲覧用のページです（{len(rows)}行 × {len(head)}列）。正本は CSV で、このファイルは `python3 scripts/build_html.py` が生成します。手で編集しないでください。", "",
           "| " + " | ".join(cell(h) for h in head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        r = (r + [""] * len(head))[:len(head)]
        out.append("| " + " | ".join(cell(c) for c in r) + " |")
    return "\n".join(out) + "\n"


def outputs(root: Path = ROOT) -> dict[Path, str]:
    """生成物 {パス: 内容}。Markdown は HTML に、CSV は表の Markdown と HTML にする"""
    out = {p.with_suffix(".html"): render(p, root) for p in sources(root)}
    for p in csv_files(root):
        md = csv_to_markdown(p, root)
        out[p.with_suffix(".md")] = md
        out[p.with_suffix(".html")] = render_text(md, p, root)
    index = root / "index.html"
    if index.exists() and (root / "data" / "tasks.csv").exists():
        out[index] = fill_auto(index.read_text(encoding="utf-8"), "tasks", tasks_table(root))
    return out


def tasks_table(root: Path = ROOT) -> str:
    """index.html に埋め込む準備タスクの表（先頭12件）。CSV を fetch しないので file:// でも表示できる"""
    head, rows = read_csv_rows(root / "data" / "tasks.csv")
    col = {h: i for i, h in enumerate(head)}
    labels = {"not_started": "未着手", "in_progress": "進行中", "blocked": "保留", "done": "完了"}

    def get(r, k):
        return r[col[k]] if k in col and col[k] < len(r) else ""
    done = sum(1 for r in rows if get(r, "status") == "done")
    todo = sum(1 for r in rows if get(r, "status") == "not_started")
    body = []
    for r in rows[:12]:
        issue = get(r, "issue_url")
        link = f'<a href="{html.escape(issue, quote=True)}">Issue</a>' if issue.startswith("https://github.com/") else ""
        body.append(f"<tr><td>{html.escape(get(r, 'priority'))}</td><td>{html.escape(get(r, 'task'))}</td>"
                    f"<td>{html.escape(labels.get(get(r, 'status'), get(r, 'status')))}</td><td>{link}</td></tr>")
    return (f'<div class="box"><div class="muted">登録タスク {len(rows)}件 / 完了 {done}件 / 未着手 {todo}件</div>'
            '<div class="scroll"><table><thead><tr><th>優先</th><th>作業</th><th>状態</th><th>Issue</th></tr></thead>'
            f'<tbody>{"".join(body)}</tbody></table></div></div>')


def fill_auto(text: str, name: str, content: str) -> str:
    pat = re.compile(rf"(<!-- AUTO:{name} -->)(.*?)(<!-- /AUTO:{name} -->)", re.S)
    return pat.sub(lambda m: f"{m.group(1)}\n{content}\n{m.group(3)}", text)


def main() -> int:
    check_only = "--check" in sys.argv
    out = outputs()
    if check_only:
        stale = [p.relative_to(ROOT).as_posix() for p, text in out.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        orphan = [p.relative_to(ROOT).as_posix() for d in SOURCE_DIRS + [DATA_DIR] for p in (ROOT / d).glob("*.html")
                  if p.read_text(encoding="utf-8").startswith("<!doctype html>\n<!-- generated") and p not in out]
        if stale or orphan:
            print("HTML が Markdown と一致しません。`python3 scripts/build_html.py` を実行してコミットしてください: "
                  + ", ".join(stale + orphan), file=sys.stderr)
            return 1
        print(f"PASS: {len(out)} HTML pages match Markdown")
        return 0
    for p, text in out.items():
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"更新しました: {len(out)} ページ")
    return 0


