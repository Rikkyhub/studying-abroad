def reader_clean(text: str) -> str:
    """読者向けのHTMLから、作業管理用の「Issue #番号」の言及を外す（元のMarkdownには残す）。
    <script> の中のデータ（案の名前など）も表示されるので対象。URL・id は 'Issue #' を含まないので変わらない"""
    for pat, rep in _READER_RULES:
        text = pat.sub(rep, text)
    return text


