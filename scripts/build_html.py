def nav(root: Path, current: Path) -> str:
    groups = GROUPS
    rel_root = "../"
    parts = [f'<a href="{rel_root}index.html">ダッシュボード</a>']
    for d, label in groups.items():
        files = sorted((root / d).glob("*.csv" if d == DATA_DIR else "*.md"))
        links = []
        for f in files:
            t = f.name if d == DATA_DIR else page_title(f)
            href = f"{rel_root}{d}/{f.stem}.html"
            cur = ' aria-current="page"' if f == current else ""
            links.append(f'<a href="{href}"{cur}>{html.escape(t)}</a>')
        parts.append(f'<details{" open" if current.parent.name == d else ""}><summary>{label}</summary>{"".join(links)}</details>')
    return "".join(parts)


def page_title(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^#\s+(.*)$", line.strip())
        if m:
            return re.sub(r"[*`]", "", m.group(1)).strip()
    return path.stem


def render(path: Path, root: Path = ROOT) -> str:
    return render_text(path.read_text(encoding="utf-8"), path, root)


def render_text(md: str, path: Path, root: Path = ROOT) -> str:
    title, body, toc = convert(md)
    title = title or path.stem
    rel = path.relative_to(root).as_posix()
    toc_html = "".join(f'<a class="t{lv}" href="#{a}">{html.escape(t)}</a>' for lv, a, t in toc if lv <= 3)
    return page_html(
        mark=GENERATED_MARK.format(src=rel),
        title=html.escape(title),
        section=GROUPS.get(path.parent.name, ""),
        body=body,
        toc=toc_html or "",
        toc_hidden="" if len(toc) > 2 else " hidden",
        nav=nav(root, path),
        src=html.escape(rel),
        src_url=f"{REPO_URL}/blob/main/{rel}",
    )


def csv_files(root: Path = ROOT) -> list[Path]:
    return sorted((root / DATA_DIR).glob("*.csv"))


def read_csv_rows(path: Path) -> tuple[list[str], list[list[str]]]:
    with path.open(newline="", encoding="utf-8-sig") as f:
        rows = list(csv.reader(f))
    return (rows[0], rows[1:]) if rows else ([], [])


def csv_to_markdown(path: Path, root: Path = ROOT) -> str:
    """CSV を Markdown の表にする。セル内の | と改行は表を壊さないよう置き換える"""
    head, rows = read_csv_rows(path)
    rel = path.relative_to(root).as_posix()

    def cell(v: str) -> str:
        return " ".join(v.replace("|", "／").split())
    out = [f"# {path.name}", "",
           f"`{rel}` を表にした閲覧用のページです（{len(rows)}行 × {len(head)}列）。正本は CSV で、このファイルは `python3 scripts/build_html.py` が生成します。手で編集しないでください。", "",
           "| " + " | ".join(cell(h) for h in head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        r = (r + [""] * len(head))[:len(head)]
        out.append("| " + " | ".join(cell(c) for c in r) + " |")
    return "\n".join(out) + "\n"


def outputs(root: Path = ROOT) -> dict[Path, str]:
    """生成物 {パス: 内容}。Markdown は HTML に、CSV は表の Markdown と HTML にする"""
    out = {p.with_suffix(".html"): render(p, root) for p in sources(root)}
    for p in csv_files(root):
        md = csv_to_markdown(p, root)
        out[p.with_suffix(".md")] = md
        out[p.with_suffix(".html")] = render_text(md, p, root)
    if (root / DATA_DIR / "pages.csv").exists() and (root / DATA_DIR / "tasks.csv").exists():
        mp = root / "docs" / ISSUE_MAP
        md = issue_map_markdown(root)
        out[mp] = md
        out[mp.with_suffix(".html")] = render_text(md, mp, root)
    index = root / "index.html"
    if index.exists() and all((root / DATA_DIR / f).exists() for f in ("tasks.csv", "pages.csv", "timeline.csv", "places.csv", "fx.csv")):
        text = index.read_text(encoding="utf-8")
        for name, content in (("summary", summary_block(root)), ("timeline", timeline_table(root)),
                              ("tasks", tasks_table(root)), ("research", pages_table(root, "research")),
                              ("plan", pages_table(root, "plan")), ("places", places_table(root)),
                              ("fx", fx_block(root)), ("budget", budget_block(root))):
            text = fill_auto(text, name, content)
        out[index] = text
    return out


