def render_text(md: str, path: Path, root: Path = ROOT) -> str:
    title, body, toc = convert(md)
    title = title or path.stem
    rel = path.relative_to(root).as_posix()
    if path.parent.name in ("research", "areas"):
        body = fold_sections(fold_notes(body), min_chars=400 if path.parent.name == "areas" else 600,
                             open_key="費用の見積" if path.parent.name == "areas" else "")
    elif rel in FOLD_DOCS:
        # 長い docs（予算・準備・QA・Issue対応表）も、節ごとに開閉できるようにする。open_key の節だけ開いておく
        body = fold_sections(body, min_chars=900, open_key=FOLD_DOCS[rel])
    if 'class="sec"' in body:
        body += "\n" + SECTION_SCRIPT
    if "@@COUNTRY-MAP@@" in md:
        import build_country_maps
        body = body.replace("@@COUNTRY-MAP@@", "<style>" + build_country_maps.CSS + "</style>" + build_country_maps.render(path.stem, root))
    if "@@ROUTE-TABLE@@" in md:
        body = body.replace("@@ROUTE-TABLE@@", ROUTE_TABLE_HTML)
    if "@@DAY-PLANNER@@" in md:
        body = body.replace("@@DAY-PLANNER@@", PLANNER_HTML)
    if "data-planner" in body:
        body += "\n" + PLANNER_SCRIPT.replace("@@PRESETS@@", route_presets(root)).replace("@@HINTS@@", planner_hints()).replace("@@DAILY@@", planner_daily_costs(root))
    if "data-route" in body:
        body += "\n" + ROUTE_SCRIPT.replace("@@PRESETS@@", route_presets(root)).replace("@@PLACES@@", route_places(root))
    if "data-cost" in body:
        body += "\n" + COST_TRIAGE_SCRIPT
    toc_html = ""
    heads = [(a, t) for lv, a, t in toc if lv == 2]
    if len(heads) >= 3:
        toc_html = '<nav class="toc" aria-label="このページの目次"><span class="label">このページ：</span>' + "".join(
            f'<a href="#{a}">{html.escape(t)}</a>' for a, t in heads) + "</nav>"
    current = f"{path.parent.name}/{path.stem}.html" if path.parent.name == "areas" else ""
    return page_html(
        mark=GENERATED_MARK.format(src=rel),
        title=html.escape(title),
        section=GROUPS.get(path.parent.name, ""),
        body=body,
        toc=toc_html,
        bar=bar("../", current),
        prefix="../",
        nav=nav(root, path),
        src=html.escape(rel),
        src_url=f"{REPO_URL}/blob/main/{rel}",
    )


