def csv_records(path: Path) -> list[dict]:
    head, rows = read_csv_rows(path)
    return [dict(zip(head, (r + [""] * len(head))[:len(head)])) for r in rows]


def read_csv_rows(path: Path) -> tuple[list[str], list[list[str]]]:
    with path.open(newline="", encoding="utf-8-sig") as f:
        rows = list(csv.reader(f))
    return (rows[0], rows[1:]) if rows else ([], [])


def esc(s: str) -> str:
    return html.escape(s, quote=True)


def sorted_pages(root: Path = ROOT) -> list[dict]:
    return sorted(csv_records(root / DATA_DIR / "pages.csv"), key=lambda r: (int(r["sort"] or 0), r["id"]))


def table(headers: list[str], rows: list[list[str]], num: tuple = (), widths: list[int] | None = None) -> str:
    """セルは生成済みHTML。num の列は右寄せ。widths は列幅の目安（%）。幅が足りない狭い画面でだけ .scroll の中で横に動く"""
    cols = "".join(f'<col style="width:{w}%">' for w in widths) if widths else ""
    colgroup = f"<colgroup>{cols}</colgroup>" if cols else ""
    th = "".join(f'<th{" class=n" if k in num else ""}>{h}</th>' for k, h in enumerate(headers))
    tr = "".join("<tr>" + "".join(f'<td{" class=n" if k in num else ""}>{c}</td>' for k, c in enumerate(r)) + "</tr>"
                 for r in rows)
    return f'<div class="scroll"><table>{colgroup}<thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table></div>'


def ref_links(refs: str, sep: str = " ・ ") -> str:
    """refs 列（; 区切りの http(s) URL）を短いドメイン名のリンクにする"""
    out = []
    for u in filter(None, (x.strip() for x in refs.split(";"))):
        host = urlparse(u).netloc.removeprefix("www.")
        out.append(f'<a href="{esc(u)}" target="_blank" rel="noopener" title="{esc(u)}">{esc(host)}</a>')
    return sep.join(out) or "－"


def num(s: str):
    try:
        d = Decimal(s)
    except (InvalidOperation, ValueError):
        return None
    return d if d.is_finite() and d > 0 else None


def fmt(d: Decimal, places: int = 2) -> str:
    q = d.quantize(Decimal(1).scaleb(-places), rounding=ROUND_HALF_UP)
    s = f"{q:,.{places}f}"
    return s[:-(places + 1)] if s.endswith("." + "0" * places) else s


