        gaps = [s.strip() for s in sents if "未確認" in s or "未入力" in s or "未計上" in s or "次" in s[:2]]
        note = "".join(gaps) or note  # 「未確認」を含む文を優先（確認日や出典の説明より、分かっていない点を先に）
