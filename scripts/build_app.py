FIELDS = ["id", "phase", "task", "deadline_kind", "deadline_note", "lead_days", "status", "priority",
          "cost_note", "next_action", "source", "issue", "note", "region"]


def load_tasks(root: Path = ROOT) -> list[dict]:
    with (root / "data" / "tasks.csv").open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    out = []
    for r in rows:
        t = {k: (r.get(k) or "").strip() for k in FIELDS}
        t["lead_days"] = int(t["lead_days"] or 0)
        t["priority"] = int(t["priority"] or 3)
        t["regions"] = [x for x in t.pop("region").split(";") if x] or ["common"]
        t.pop("issue")  # 保守者向け情報は画面に出さない
        t["source"] = t["source"] if t["source"].startswith("http") else ""
        out.append(t)
    return out


def css_vars(tok: dict) -> str:
    def block(sel: str, d: dict) -> str:
        return sel + "{" + "".join(f"--c-{k}:{v};" for k, v in d.items()) + "}"

    light, dark = tok["color"]["light"], tok["color"]["dark"]
    s = tok["space"]
    r = tok["radius"]
    f = tok["font"]
    common = (":root{" + "".join(f"--s-{k}:{v}px;" for k, v in s.items())
              + "".join(f"--r-{k}:{v}px;" for k, v in r.items())
              + f"--font:{f['family']};--fs-caption:{f['size']['caption']}px;--fs-body:{f['size']['body']}px;"
                f"--fs-bodyL:{f['size']['bodyLarge']}px;--fs-title:{f['size']['title']}px;--fs-head:{f['size']['headline']}px;"
                f"--lh-tight:{f['lineHeight']['tight']};--lh-body:{f['lineHeight']['body']};"
                f"--sh-card:{tok['elevation']['card']};--sh-sheet:{tok['elevation']['sheet']};--touch:{tok['touchTarget']}px}}")
    return "\n".join([
        common,
        block(":root", light),
        "@media (prefers-color-scheme:dark){" + block(':root:not([data-theme="light"])', dark) + "}",
        block(':root[data-theme="dark"]', dark),
        block(':root[data-theme="light"]', light),
    ])


