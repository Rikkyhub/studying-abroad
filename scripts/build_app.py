def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("app.html が古いです。`py scripts/build_app.py` を実行してコミットしてください", file=sys.stderr)
            return 1
        print(f"PASS: app.html is current ({len(text.encode('utf-8')) // 1024} KB)")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"app.html: {len(text.encode('utf-8')) // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
